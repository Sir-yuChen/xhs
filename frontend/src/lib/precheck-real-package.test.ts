describe("真包 26/26（规则解析 + 精确对齐）", () => {
  const media = FILES.map((f, i) => ({
    group: "sku", index: i, rel_path: `SKU/${f}`, file_name: f,
  })) as PrecheckMedia[];
  const list = localSkuImageList(media);

  it("26 个 SKU 名全部命中，且每个都指回**自己那张**（不是别人的）", () => {
    const results = SKU_NAMES.map((n, i) => lookupLocalSkuImage(list, n));
    const misses = SKU_NAMES.filter((n) => lookupLocalSkuImage(list, n) === null);
    expect(misses).toEqual([]);
    //: 逐条核对指向正确（防「错配」这个真风险）
    SKU_NAMES.forEach((n, i) => {
      expect(results[i]).toBe(`SKU/${FILES[i]}`);
    });
  });

  it("26 条结果**两两不同**（没有两条规格指向同一张图 = 没有吞并）", () => {
    const picked = SKU_NAMES.map((n) => lookupLocalSkuImage(list, n));
    expect(new Set(picked).size).toBe(26);
  });

  it("前缀重叠对不误配：`SKU02` 与 `SKU03` 各自指回自己", () => {
    expect(lookupLocalSkuImage(list, SKU_NAMES[1])).toBe(`SKU/${FILES[1]}`);
    expect(lookupLocalSkuImage(list, SKU_NAMES[2])).toBe(`SKU/${FILES[2]}`);
  });

  it("解析后的 key 与表格 SKU 名同形（可直接等值比对）", () => {
    FILES.forEach((f, i) => {
      expect(skuImageNameFromFile(f)).toBe(SKU_NAMES[i]);
    });
  });
});
