"""出图提示词的**公共约束集**（设计 17 §13.3.7.7，v2.21）。

## 为什么要有这个模块

在它之前，项目里有 **4 处各自拼出图提示词**，措辞互不一致：

| 位置 | 用途 | 原来写的是 |
|---|---|---|
| `qianfan._default_detail_image_prompt` | 商品详情图 | 「竖版长图构图，干净背景，突出商品主体与卖点排版」 |
| `media_generation._default_image_prompt` | 笔记配图 | 「干净背景的商品封面图…竖版构图，突出卖点」 |
| `media_generation._default_video_prompt` | 笔记视频 | 「竖版构图，突出商品主体与使用场景」 |
| `note-gen` 各业务点 | 文本类 | 各自成段 |

问题有两层：

1. **重复**：「竖版构图」「干净背景」「突出主体」这几句在 3 处各写一遍 —— 改一处漏两处
   （DEF-044「同一语义不留两份实现」）。
2. **缺失**：**防漂移约束只加在了详情图那一处**。市场调研（`docs/02_设计文档/18_…§5-③`）
   的结论是：批量出图最大的问题是**风格漂移**，而解法（固定光位 / 保留材质 / 禁止改形）
   对**所有**电商出图都成立 —— 只保护一个业务点等于没保护。

## 结构：按**用途**分档，而不是一个大字符串

⚠️ 不同用途的约束**确实不同**，不能一锅炖：

| 用途 | 典型约束差异 |
|---|---|
| `DETAIL`（详情图） | 竖版 3:4，画面干净无文字（要能直接进详情页） |
| `COVER`（笔记配图/封面） | 竖版，**允许留出标题位置**（封面要叠字） |
| `VIDEO`（视频） | 竖版，强调**动态场景**，不说「画面静止」类约束 |

所以本模块导出的是**可组合的约束行**（`common_*` + 用途专属），
由各调用点按需拼装 —— 而不是导出「唯一的那个大 prompt」。

⚠️ **但同一条约束只有一份定义**：`common` 那几条（防漂移三条）是**所有用途共享**的，
改一次全生效。这才是「公共」的意义 —— 公共的是**约束库**，不是**成品字符串**。
"""

from __future__ import annotations

# --------------------------------------------------------------------------- #
# 公共约束（**所有电商出图用途共享**，改一次全生效）
# --------------------------------------------------------------------------- #
#: 防漂移三条 —— 市场调研实测有效的具体措辞（不是泛泛的「好看一点」）。
#: ⚠️ 顺序固定：光位 → 材质 → 形状。同组内**逐字复用**才有一致性（这就是「一致性锁」）。
GENERATION_SAFETY_LINES: tuple[str, ...] = (
    "- 统一光位：左上方 45° 柔光 + 右侧补光板，阴影自然、方向一致；",
    "- 保留商品真实材质与颜色（金属保留高光与反射、布料保留纹理），避免塑胶感；",
    "- 严格保持商品外观、形状、比例与参考图一致，禁止改变产品形状或添加不存在的部件；",
)

#: 合规约束 —— 平台侧通用（详情图 / 配图 / 视频都适用）。
#: ⚠️ 与 `product_note_service` 的广告法护栏同源纪律：画面里出现价格/logo 会带来
#: 平台审核风险（价格还可能与实际不符）。
PLATFORM_SAFE_LINES: tuple[str, ...] = (
    "- 图中不要出现文字水印、logo 或价格标签。",
)

#: 画质约束（通用）。
QUALITY_LINES: tuple[str, ...] = (
    "- 突出商品主体与核心卖点，画面干净、有质感；",
)


# --------------------------------------------------------------------------- #
# 用途枚举
# --------------------------------------------------------------------------- #
#: 商品详情图（详情页用，竖版 3:4，必须无文字）。
USE_DETAIL: str = "detail"
#: 笔记封面 / 配图（要留出叠标题的位置，故与详情图的约束不同）。
USE_COVER: str = "cover"
#: 商品展示视频。
USE_VIDEO: str = "video"

#: 用途 → 该用途专属的「构图」行（**差异只在这里**）。
_LAYOUT_LINES: dict[str, tuple[str, ...]] = {
    USE_DETAIL: ("- 竖版 3:4 构图，适合电商商品详情页展示；",),
    USE_COVER: (
        "- 竖版 3:4 构图，适合小红书笔记封面；",
        "- 画面上方约 1/4 留白，便于后期叠加标题文字；",
    ),
    USE_VIDEO: (
        "- 竖版 9:16 构图，适合短视频展示；",
        "- 画面表现商品在实际使用场景中的动态感；",
    ),
}


def layout_lines(use: str) -> tuple[str, ...]:
    """用途专属的构图行（未知用途 ⇒ 回落详情图口径，不静默给空）。"""
    return _LAYOUT_LINES.get(use, _LAYOUT_LINES[USE_DETAIL])


def requirement_lines(use: str = USE_DETAIL) -> tuple[str, ...]:
    """该用途的**完整**出图约束行（构图 + 画质 + 防漂移 + 合规）。

    ⚠️ 顺序有意为之：先说「画什么」（构图/画质），再说「怎么不跑偏」（防漂移），
    最后说「不要什么」（合规）。模型对**靠后**的约束遵守度更稳，故把禁止项放最后。
    """
    return (*layout_lines(use), *QUALITY_LINES, *GENERATION_SAFETY_LINES, *PLATFORM_SAFE_LINES)


def requirement_block(use: str = USE_DETAIL) -> str:
    """带标题的约束段（供拼进 prompt 的调用点用）。"""
    return "\n".join(("出图要求：", *requirement_lines(use)))


def requirement_inline(use: str = USE_DETAIL) -> str:
    """**单行**形式（供 `"；".join(...)` 那类紧凑拼装用）。

    ⚠️ 去掉行首的 `- `，因为单行形式里用 `；` 分隔，留着破折号会显得像列点残留。
    """
    return "；".join(line[2:] if line.startswith("- ") else line for line in requirement_lines(use))


__all__ = [
    "GENERATION_SAFETY_LINES",
    "PLATFORM_SAFE_LINES",
    "QUALITY_LINES",
    "USE_COVER",
    "USE_DETAIL",
    "USE_VIDEO",
    "layout_lines",
    "requirement_block",
    "requirement_inline",
    "requirement_lines",
]
